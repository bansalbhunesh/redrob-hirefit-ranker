"""Build a complete, validated ALTERNATIVE submission from the novel rank-fusion
(fusion-raw: RRF over 6 ranker families, top-lock 20). Written to a NON-golden path
(experiments/fusion_raw_submission.csv) -- the frozen golden submission.csv is never
touched. Self-verifies composite vs golden on the blind arbiter + independent sets.

The score column is rank-monotonic (strictly descending, in (0,1)): fusion reorders
candidates relative to the hand score, and the challenge metric scores by candidate-id
ORDER (NDCG/MAP/P@10), so a confidence-style monotone score keeps the CSV valid for the
official validator without altering ranking. Reasoning text is generated by the real
build_reason machinery so the CSV is a genuine drop-in.
"""
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, "src")
sys.path.insert(0, "experiments")

from _lib import load_pool  # noqa: E402
from exp_rankfusion import rankings as build_rankings  # noqa: E402
from exp_rankfusion_guarded import build_top  # noqa: E402
from redrob_ranker.eval_harness import evaluate, load_labels  # noqa: E402
from redrob_ranker.io import write_submission  # noqa: E402
from redrob_ranker.pipeline import RankerConfig, run_ranking  # noqa: E402
from redrob_ranker.reasoning import build_reason  # noqa: E402
from redrob_ranker.validation import validate_rows  # noqa: E402

OUT = Path("experiments/fusion_raw_submission.csv")
LAB = Path("C:/Users/bhune/india-runs-compare-lab/artifacts")


def main():
    recs, base_ids = load_pool()
    ranks = build_rankings(recs)
    fusion_ids = build_top(recs, ranks, "raw")  # 100 cids, novel ordering
    assert len(fusion_ids) == 100

    # Full pipeline once -> real (candidate, features) for reasoning.
    with tempfile.TemporaryDirectory() as tmp:
        res = run_ranking(Path("candidates.jsonl"), Path(tmp) / "o.csv",
                          RankerConfig(top_k=100, candidate_pool_size=0,
                                       max_candidates=None, bm25_backend="auto"))
    feat_by = {c["candidate_id"]: (c, f) for c, f, _ in (res.raw_ranked or [])}

    rows, used = [], set()
    n = len(fusion_ids)
    for rank, cid in enumerate(fusion_ids, start=1):
        cand, feat = feat_by[cid]
        rows.append({
            "candidate_id": cid,
            "rank": rank,
            "score": f"{(n - rank + 1) / (n + 1):.6f}",   # strictly descending in (0,1)
            "reasoning": build_reason(cand, feat, rank, used_quotes=used),
        })

    errors = validate_rows(rows, expected=100)
    if errors:
        print("VALIDATION FAILED:")
        for e in errors:
            print("  ", e)
        return
    write_submission(OUT, rows)
    print(f"wrote {OUT}  (golden submission.csv untouched)")

    # Verify outperformance across label sets.
    def comp(ids, ls):
        return evaluate(ids, ls).composite
    sets = ["h2_availblind_labels", "merged_j1", "merged_j2", "merged_j3",
            "relabel_j4", "relabel_g25", "blind_test_frozen"]
    print(f"\n{'label set':<22}{'golden':>10}{'fusion-raw':>12}{'delta':>10}")
    wins = 0
    for name in sets:
        p = LAB / f"{name}.jsonl"
        if not p.exists():
            continue
        ls = load_labels(p)
        g, fr = comp(base_ids, ls), comp(fusion_ids, ls)
        wins += fr > g + 1e-9
        print(f"{name:<22}{g:>10.4f}{fr:>12.4f}{fr - g:>+10.4f}")
    print(f"\nfusion-raw > golden on {wins} label sets (validated alternative submission).")


if __name__ == "__main__":
    import multiprocessing as mp
    mp.freeze_support()
    main()
